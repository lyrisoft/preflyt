import { BadRequestException } from "@nestjs/common";
import { posix } from "node:path";
import { parse } from "yaml";
import type { RepositorySnapshot } from "../github/repository-profile.js";
import type { WorkflowRule } from "./pipeline-workflow.js";

export type ContainerScanSetup = {
  dockerfiles: string[];
  dockerfile: string | null;
  buildContext: string | null;
  needsSelection: boolean;
};

const repositoryPath = (path: unknown): path is string =>
  typeof path === "string" &&
  path.length > 0 &&
  path.length <= 512 &&
  !/[\u0000-\u001f\u007f\\]/.test(path) &&
  !posix.isAbsolute(path) &&
  !path.split("/").includes("..") &&
  !path.split("/").includes(".git") &&
  !path.includes("{{") &&
  !/^[a-z]+:/i.test(path);

/** Detect paths only. Repository Dockerfiles are never built by the API. */
export function containerScanSetup(
  snapshot: RepositorySnapshot,
  rules: WorkflowRule[],
  selected?: string,
): ContainerScanSetup | null {
  const enabled = rules.some(
    (rule) => rule.id === "containers.scan" && !rule.workflowCommand,
  );
  if (!enabled) {
    if (selected)
      throw new BadRequestException(
        "This policy does not use the built-in container scan",
      );
    return null;
  }
  const dockerfiles = [
    ...new Set(
      snapshot.files
        .filter(
          (file) =>
            repositoryPath(file.path) &&
            /(^|\/)(Dockerfile(?:\.[^/]+)?|[^/]+\.Dockerfile)$/.test(file.path),
        )
        .map((file) => file.path),
    ),
  ].sort();
  if (selected && !dockerfiles.includes(selected))
    throw new BadRequestException(
      "The selected Dockerfile was not found at this commit. Refresh setup and choose a detected Dockerfile.",
    );
  let installed: string | undefined;
  const previous = snapshot.files.find(
    (file) => file.path === ".github/workflows/preflyt.yml",
  )?.content;
  if (!selected && previous?.startsWith("# Preflyt pull request workflow")) {
    try {
      const steps = parse(previous)?.jobs?.preflyt_checks?.steps;
      installed = Array.isArray(steps)
        ? steps.find(
            (step) => step?.name === "Build the image for container scanning",
          )?.env?.PREFLYT_DOCKERFILE
        : undefined;
    } catch {
      /* An invalid installed workflow is regenerated by the caller. */
    }
  }
  const dockerfile =
    selected ||
    (installed && dockerfiles.includes(installed)
      ? installed
      : dockerfiles.length === 1
        ? dockerfiles[0]!
        : null);
  // A literal build-push-action context is better evidence than a directory guess.
  // Ignore remote contexts, expressions, build execution and conflicting contexts.
  const contexts = new Set<string>();
  if (dockerfile)
    for (const file of snapshot.files.filter(
      (file) =>
        /^\.github\/workflows\/[^/]+\.ya?ml$/.test(file.path) && file.content,
    )) {
      try {
        const workflow = parse(file.content!);
        for (const job of Object.values(workflow?.jobs ?? {}) as any[]) {
          for (const step of Array.isArray(job?.steps) ? job.steps : []) {
            if (
              typeof step?.uses === "string" &&
              step.uses.startsWith("docker/build-push-action@") &&
              repositoryPath(step.with?.file) &&
              posix.normalize(step.with.file) === dockerfile &&
              repositoryPath(step.with?.context) &&
              (posix.normalize(step.with.context) === "." ||
                snapshot.files.some((file) =>
                  file.path.startsWith(
                    posix.normalize(step.with.context) + "/",
                  ),
                ))
            )
              contexts.add(posix.normalize(step.with.context));
          }
        }
      } catch {
        /* Unreadable workflows cannot supply build context. */
      }
    }
  return {
    dockerfiles,
    dockerfile,
    buildContext: dockerfile
      ? contexts.size === 1
        ? [...contexts][0]!
        : posix.dirname(dockerfile)
      : null,
    needsSelection: dockerfiles.length > 1 && !dockerfile,
  };
}

export function requireContainerSelection(setup: ContainerScanSetup | null) {
  if (setup?.needsSelection)
    throw new BadRequestException(
      "Choose a Dockerfile for container scanning before generating, downloading or creating the workflow PR.",
    );
}
